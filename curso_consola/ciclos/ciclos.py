# Equivale a: ciclos/ciclos.php · ciclos.js · Ciclos.cs · PSeInt módulo 4
#
# Un ciclo repite un bloque de instrucciones. Python solo tiene DOS: for y
# while. Los demás lenguajes del curso tienen más, pero todos se reducen a
# estos dos:
#
#   Situación                         PSeInt      PHP/JS/C#    Python
#   -------------------------------   ---------   ----------   -----------------
#   Sé cuántas veces repetir          Para        for          for ... in range()
#   Recorrer una colección            Para        foreach      for ... in lista
#   No sé cuántas veces; quizá cero   Mientras    while        while
#   Al menos una vez                  Repetir     do-while     while True + break
# ============================================================================

